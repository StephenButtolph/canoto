package generate

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/StephenButtolph/canoto"
)

const (
	defaultCanotoSelector    = "canoto"
	libraryFileName          = "canoto.go"
	generatedLibraryFileName = "canoto.canoto.go"
	raceLibraryFileName      = "race.go"
	noRaceLibraryFileName    = "norace.go"
	readWrite                = 0o640
	readWriteExecute         = 0o750

	goGeneratePrefix = "//go:generate "
	doNotEdit        = `// Code generated by canoto. DO NOT EDIT.
// versions:
// 	canoto ` + canoto.Version + `

`
)

// Library generates the canoto serialization primitives package in the provided
// folder.
//
// Specifically, if "./internal" is provided, this will generate the package
// "./internal/canoto" with the serialization primitives included in:
//
//   - "./internal/canoto/canoto.go"
//   - "./internal/canoto/canoto.canoto.go"
//   - "./internal/canoto/race.go"
//   - "./internal/canoto/norace.go"
func Library(parentDir string) error {
	library := filepath.Join(parentDir, defaultCanotoSelector)
	if err := os.MkdirAll(library, readWriteExecute); err != nil {
		return fmt.Errorf("failed to create directory %q: %w", library, err)
	}

	// The go:generate directives regenerate canoto from this module, so they
	// are removed, along with the blank line that follows them.
	codeWithoutPrefix := canoto.Code
	if directives, code, ok := strings.Cut(canoto.Code, "\n\n"); ok && strings.HasPrefix(directives, goGeneratePrefix) {
		codeWithoutPrefix = code
	}
	files := []struct {
		name string
		code string
	}{
		{name: libraryFileName, code: doNotEdit + codeWithoutPrefix},
		{name: generatedLibraryFileName, code: canoto.GeneratedCode},
		{name: raceLibraryFileName, code: doNotEdit + canoto.RaceCode},
		{name: noRaceLibraryFileName, code: doNotEdit + canoto.NoRaceCode},
	}
	for _, f := range files {
		path := filepath.Join(library, f.name)
		if err := os.WriteFile(path, []byte(f.code), readWrite); err != nil {
			return fmt.Errorf("failed to write file %q: %w", path, err)
		}
	}
	return nil
}
