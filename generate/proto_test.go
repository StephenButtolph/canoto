package generate

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/StephenButtolph/canoto"
)

// TestProtoTypeReferences verifies that only types declared in the file are
// referenced as messages, and that they can not be confused with proto scalar
// types or keywords.
func TestProtoTypeReferences(t *testing.T) {
	require := require.New(t)

	const want = `// Code generated by canoto. DO NOT EDIT.
// versions:
// 	canoto ${version}
// source: testdata/proto_type_references.go

syntax = "proto3";

package testdata;

message Foo {
  sint64 A = 1;
}

message Foo__Pointer {
  Foo value = 1;
}

message double {
  sint64 A = 1;
}

message double__Pointer {
  .testdata.double value = 1;
}

message message {
  sint64 A = 1;
}

message message__Pointer {
  .testdata.message value = 1;
}

message Outer {
  Foo Local = 1;
  bytes Imported = 2;
  .testdata.double Double = 3;
  .testdata.message Message = 4;
  repeated Foo__Pointer Pointers = 5;
}

message Outer__Pointer {
  Outer value = 1;
}

message Generic {
  bytes Param = 1;
  bytes Imported = 2;
}

message Generic__Pointer {
  Generic value = 1;
}
`

	const filePath = "testdata/proto_type_references.go"
	fs := token.NewFileSet()
	f, err := parser.ParseFile(fs, filePath, nil, parser.ParseComments)
	require.NoError(err)

	var opts Options
	opts.init()
	packageName, messages, err := parse(fs, f, opts)
	require.NoError(err)

	var sb strings.Builder
	require.NoError(writeProto(&sb, filePath, packageName, messages))
	require.Equal(makeTemplate(want, map[string]string{"version": canoto.Version}), sb.String())

	// The imported field must not be cast to the type parameter.
	generic := messages[len(messages)-1]
	require.Equal("Generic", generic.name)
	require.Equal("T2(", generic.fields[0].templateArgs["castOpen"])
	require.Empty(generic.fields[1].templateArgs["castOpen"])
}
